import fs from 'node:fs';
import assert from 'node:assert/strict';
const vercel = JSON.parse(fs.readFileSync(new URL('../vercel.json', import.meta.url), 'utf8'));
assert.equal(vercel.outputDirectory, 'public');
assert.ok(!fs.existsSync(new URL('../api/[...path].js', import.meta.url)), 'tidak memakai catch-all berbasis nama-file');
assert.deepEqual(vercel.rewrites, [{ source: '/api/:path*', destination: '/api?__p=:path*' }], 'semua /api/* di-rewrite ke satu fungsi');
assert.ok(fs.existsSync(new URL('../api/index.js', import.meta.url)));
const server = fs.readFileSync(new URL('../server/server.cjs', import.meta.url), 'utf8');
assert.match(server, /if \(require\.main === module\) app\.listen/);
assert.match(server, /module\.exports = app/);
assert.match(server, /TURSO_DATABASE_URL/);
assert.match(server, /TURSO_AUTH_TOKEN/);
assert.match(server, /require\('libsql'\)/);
assert.match(server, /SQLite lokal \/tmp tidak persisten/);
assert.equal(vercel.installCommand, 'npm install --package-lock=false');
const api = fs.readFileSync(new URL('../public/assets/js/ui/api.js', import.meta.url), 'utf8');
assert.match(api, /export const API =/);
assert.doesNotMatch(api, /http:\/\/localhost:8000'\s*:\s*raw/);
const core = fs.readFileSync(new URL('../public/assets/js/engine/core.js', import.meta.url), 'utf8');
assert.match(core, /export const creatorAge = \(\) => ageYears\(\)/);
assert.doesNotMatch(core, /qaCreatorAge/);
for (let i=1;i<=6;i++) assert.ok(fs.existsSync(new URL(`../public/assets/img/avatars/avatar-${i}.svg`, import.meta.url)));
console.log('PASS: Vercel entrypoints, same-origin API, age-bypass removal and avatar assets');
